'use strict';

/**
 * Key Issuer vault logic (no Electron dependency, so it can be tested with `node --test`).
 *
 * The vault holds 3 Ed25519 key pairs. Each private key is encrypted with the vendor's passphrase
 * (scrypt + AES-256-GCM). Only one key is "active" for signing; the other two are spares so the
 * vendor can switch keys later without rebuilding the server app.
 */

const crypto = require('crypto');
const codec = require('./license-codec');

const KEY_COUNT = 3;
const MIN_PASSPHRASE = 12;
const DAY_MS = 86400000;
const SCRYPT = { N: 32768, r: 8, p: 1, maxmem: 128 * 1024 * 1024 };

function encryptPrivate(privateKey, passphrase) {
  const salt = crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const key = crypto.scryptSync(passphrase, salt, 32, SCRYPT);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const der = privateKey.export({ format: 'der', type: 'pkcs8' });
  const data = Buffer.concat([cipher.update(der), cipher.final()]);
  return {
    salt: salt.toString('hex'), iv: iv.toString('hex'),
    tag: cipher.getAuthTag().toString('hex'), data: data.toString('hex'),
  };
}

function decryptPrivate(enc, passphrase) {
  try {
    const key = crypto.scryptSync(passphrase, Buffer.from(enc.salt, 'hex'), 32, SCRYPT);
    const decipher = crypto.createDecipheriv('aes-256-gcm', key, Buffer.from(enc.iv, 'hex'));
    decipher.setAuthTag(Buffer.from(enc.tag, 'hex'));
    const der = Buffer.concat([decipher.update(Buffer.from(enc.data, 'hex')), decipher.final()]);
    return crypto.createPrivateKey({ key: der, format: 'der', type: 'pkcs8' });
  } catch {
    throw new Error('Wrong passphrase');
  }
}

function checkPassphrase(passphrase) {
  if (typeof passphrase !== 'string' || passphrase.length < MIN_PASSPHRASE)
    throw new Error(`Passphrase must be at least ${MIN_PASSPHRASE} characters`);
}

function createVault(passphrase) {
  checkPassphrase(passphrase);
  const keys = [];
  for (let id = 1; id <= KEY_COUNT; id++) {
    const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
    keys.push({
      id,
      publicKey: codec.publicKeyHex(publicKey),
      private: encryptPrivate(privateKey, passphrase),
      createdAt: new Date().toISOString(),
    });
  }
  return { version: 1, activeKeyId: 1, keys, issued: [] };
}

function findKey(vault, id) {
  const k = vault.keys.find(x => x.id === id);
  if (!k) throw new Error('Unknown key number');
  return k;
}

function setActiveKey(vault, id) {
  const k = findKey(vault, id);
  if (!k.private) throw new Error(`Key ${id} has no private key on this computer (restore it from its backup first)`);
  vault.activeKeyId = id;
}

function parseExpiry(expiry) {
  if (expiry === null || expiry === undefined || expiry === '') return 0; // permanent
  if (!/^\d{4}-\d{2}-\d{2}$/.test(expiry)) throw new Error('Expiry must be a date like 2027-12-31');
  const day = Math.floor(Date.parse(expiry + 'T00:00:00Z') / DAY_MS);
  if (!Number.isFinite(day) || day <= Math.floor(Date.now() / DAY_MS) || day > 65535)
    throw new Error('Expiry must be a future date');
  return day;
}

/**
 * purpose: 'activate' | 'reset'. Returns the code and records it in vault.issued.
 */
function issue(vault, passphrase, { purpose, requestCode, expiry, customer }) {
  const req = codec.decodeRequest(requestCode);
  if (!req) throw new Error('The Request Code is not valid. Check that it was copied completely.');
  const p = purpose === 'reset' ? codec.PURPOSE.RESET : codec.PURPOSE.ACTIVATE;
  const name = String(customer || '').trim();
  if (p === codec.PURPOSE.ACTIVATE && !name) throw new Error('Enter the customer name');
  if (Buffer.byteLength(name, 'utf8') > codec.MAX_NAME) throw new Error(`Customer name is too long (max ${codec.MAX_NAME} bytes)`);

  const key = findKey(vault, vault.activeKeyId);
  if (!key.private) throw new Error('The active key has no private key on this computer');
  const privateKey = decryptPrivate(key.private, passphrase);

  const expiryDay = p === codec.PURPOSE.ACTIVATE ? parseExpiry(expiry) : 0;
  const code = codec.issueCode(privateKey, {
    keyId: key.id, purpose: p, machineId: req.machineId, nonce: req.nonce, expiryDay, name: p === codec.PURPOSE.ACTIVATE ? name : '',
  });
  vault.issued.push({
    at: new Date().toISOString(), purpose: purpose === 'reset' ? 'reset' : 'activate',
    customer: name, expires: expiryDay ? expiry : 'permanent', keyId: key.id, requestCode,
  });
  return code;
}

/** Text of a ready-to-use server/license-keys.js containing the 3 public keys. */
function exportLicenseKeysJs(vault) {
  const lines = vault.keys.map(k => `  { id: ${k.id}, publicKey: '${k.publicKey}', retired: false },`);
  return [
    "'use strict';",
    '',
    '// Generated by the Key Issuer. Public keys only: they can verify codes but never create them.',
    '// To retire a leaked key set `retired: true` for it and ship a new server build.',
    'module.exports = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

/** A backup file for one key (the private key stays encrypted with the passphrase). */
function exportKeyBackup(vault, id) {
  const k = findKey(vault, id);
  if (!k.private) throw new Error(`Key ${id} has no private key on this computer`);
  return JSON.stringify({ type: 'panic-alarm-key-backup', version: 1, key: k }, null, 2);
}

/** Removes the private half of a spare key from this computer (after it was backed up offline). */
function removePrivate(vault, id) {
  const k = findKey(vault, id);
  if (id === vault.activeKeyId) throw new Error('Cannot remove the private key of the active key');
  k.private = null;
}

function importKeyBackup(vault, text, passphrase) {
  let b;
  try { b = JSON.parse(text); } catch { throw new Error('Not a valid key backup file'); }
  if (!b || b.type !== 'panic-alarm-key-backup' || !b.key || !b.key.private) throw new Error('Not a valid key backup file');
  const existing = findKey(vault, b.key.id);
  if (existing.publicKey !== b.key.publicKey) throw new Error('This backup belongs to a different set of keys');
  decryptPrivate(b.key.private, passphrase); // proves the passphrase fits
  existing.private = b.key.private;
}

function verifyPassphrase(vault, passphrase) {
  const k = vault.keys.find(x => x.private);
  if (!k) throw new Error('No private key on this computer');
  decryptPrivate(k.private, passphrase);
}

module.exports = {
  createVault, setActiveKey, issue, exportLicenseKeysJs, exportKeyBackup, importKeyBackup,
  removePrivate, verifyPassphrase, KEY_COUNT, MIN_PASSPHRASE,
};
